"""Generates ConfidentialityProfileTable.g.cs from DICOM PS3.15 Table E.1-1.

Usage: python generate_profile_table.py <path-to-part15.xml> <output.cs>
Source: https://dicom.nema.org/medical/dicom/current/source/docbook/part15/part15.xml
"""
import sys
import xml.etree.ElementTree as ET

NS = {"d": "http://docbook.org/ns/docbook"}
XML_ID = "{http://www.w3.org/XML/1998/namespace}id"


def text(el):
    return " ".join("".join(el.itertext()).split())


def main(src, out):
    root = ET.parse(src).getroot()
    edition = ""
    for sub in root.iter("{http://docbook.org/ns/docbook}subtitle"):
        edition = text(sub)
        break
    table = next(t for t in root.iter("{http://docbook.org/ns/docbook}table") if t.get(XML_ID) == "table_E.1-1")
    rows = table.findall(".//d:tbody/d:tr", NS)
    entries = []
    for tr in rows:
        cells = [text(td) for td in tr.findall("d:td", NS)]
        if len(cells) < 15:
            continue
        name, tag = cells[0], cells[1]
        tag = tag.strip("()").replace(",", "").upper().replace("X", "x")
        if len(tag) != 8:
            continue
        actions = [c.replace(" ", "") for c in cells[4:15]]
        entries.append((name, tag, actions))

    def q(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

    lines = [
        "// <auto-generated>",
        f"// Generated by tools/deid/generate_profile_table.py from DICOM PS3.15 Table E.1-1 ({edition}).",
        "// Columns: Basic, Retain Safe Private, Retain UIDs, Retain Device Identity, Retain Institution Identity,",
        "// Retain Patient Characteristics, Retain Longitudinal Full Dates, Retain Longitudinal Modified Dates,",
        "// Clean Descriptors, Clean Structured Content, Clean Graphics.",
        "// </auto-generated>",
        "namespace BetterDicomViewer.Core.Deidentification;",
        "",
        "internal static partial class ConfidentialityProfileTable",
        "{",
        f"    public const string Edition = {q(edition)};",
        "",
        "    public static readonly ProfileEntry[] Entries =",
        "    [",
    ]
    for name, tag, a in entries:
        lines.append(f"        new({q(name)}, {q(tag)}, {', '.join(q(x) for x in a)}),")
    lines += ["    ];", "}", ""]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{len(entries)} entries from {edition}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
